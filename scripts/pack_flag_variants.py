"""Build multiple solution JSONs for an nvcc-flag sweep.

For each entry in VARIANTS, this script:
  1. Creates ``artifacts/staging/variants/<name>/`` with a copy of
     ``solution/python/kernel.cu`` and a variant-specific ``kernel.py``
     whose ``extra_cuda_cflags`` is overridden to the given list.
  2. Packs that directory into a solution JSON at
     ``artifacts/staging/variants/<name>.solution.json``.

The resulting solution JSONs can be passed to
``scripts/run_modal_compare.py`` as a comma-separated ``--solutions`` list
for a paired benchmark (all variants on the same workloads in one Modal
session).
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from flashinfer_bench import BuildSpec
from flashinfer_bench.agents import pack_solution_from_files

DEF_NAME = "dsa_sparse_attention_h16_ckv512_kpe64_topk2048_ps64"
STAGING = PROJECT_ROOT / "artifacts" / "staging" / "variants"
SRC_CU = PROJECT_ROOT / "solution" / "python" / "kernel.cu"

# Each variant = (name, list of extra_cuda_cflags).
# Each list is PASSED AS-IS to tvm_ffi.cpp.build's extra_cuda_cflags.
_BASE_FLAGS = [
    "-gencode=arch=compute_100a,code=sm_100a",
    "-O3",
    "--use_fast_math",
    "-std=c++17",
    "-Xcompiler",
    "-fPIC",
]

VARIANTS: list[tuple[str, list[str]]] = [
    ("A_baseline", list(_BASE_FLAGS)),
    ("B_expensive", list(_BASE_FLAGS) + [
        "-Xptxas=-allow-expensive-optimizations=true",
        "-DNDEBUG",
    ]),
    ("C_regs72", list(_BASE_FLAGS) + ["-maxrregcount=72"]),
    ("D_regs64", list(_BASE_FLAGS) + ["-maxrregcount=64"]),
    ("E_dlcm_ca", list(_BASE_FLAGS) + ["-Xptxas=-dlcm=ca"]),
    ("F_combo_BxC", list(_BASE_FLAGS) + [
        "-Xptxas=-allow-expensive-optimizations=true",
        "-DNDEBUG",
        "-maxrregcount=72",
    ]),
    ("G_regs96", list(_BASE_FLAGS) + ["-maxrregcount=96"]),
]

_KERNEL_PY_TEMPLATE = '''"""JIT-compile kernel.cu with a specific nvcc flag set.

This file is auto-generated by scripts/pack_flag_variants.py.
Variant: {variant_name}
"""

from __future__ import annotations

from pathlib import Path

import tvm_ffi

_MOD_DIR = Path(__file__).resolve().parent
_KERNEL_CU = str(_MOD_DIR / "kernel.cu")

_MODULE_NAME = "wombat_dsa_{variant_name}"

_EXTRA_CUDA_CFLAGS = {flags_repr}

_EXTRA_CFLAGS = [
    "-O3",
    "-std=c++17",
    "-fPIC",
]


def _build_and_load():
    lib_path = tvm_ffi.cpp.build(
        name=_MODULE_NAME,
        cuda_files=[_KERNEL_CU],
        extra_cuda_cflags=_EXTRA_CUDA_CFLAGS,
        extra_cflags=_EXTRA_CFLAGS,
        extra_include_paths=[str(_MOD_DIR)],
    )
    return tvm_ffi.load_module(lib_path)


_mod = _build_and_load()
_kernel_fn = getattr(_mod, "kernel")


def run(q_nope, q_pe, ckv_cache, kpe_cache, sparse_indices, sm_scale, out, lse):
    _kernel_fn(
        q_nope,
        q_pe,
        ckv_cache,
        kpe_cache,
        sparse_indices,
        float(sm_scale) if not isinstance(sm_scale, float) else sm_scale,
        out,
        lse,
    )
'''


def _write_variant(name: str, flags: list[str]) -> Path:
    """Stage variant <name> under STAGING/<name>/ and pack a solution JSON."""
    src_dir = STAGING / name
    src_dir.mkdir(parents=True, exist_ok=True)

    shutil.copy(SRC_CU, src_dir / "kernel.cu")

    kernel_py = _KERNEL_PY_TEMPLATE.format(
        variant_name=name,
        flags_repr=repr(flags),
    )
    (src_dir / "kernel.py").write_text(kernel_py)

    spec = BuildSpec(
        language="python",
        target_hardware=["cuda"],
        entry_point="kernel.py::run",
        destination_passing_style=True,
    )
    sol = pack_solution_from_files(
        path=str(src_dir),
        spec=spec,
        name=f"wombat_dsa_variant_{name}",
        definition=DEF_NAME,
        author="Wombat",
    )
    out = STAGING / f"{name}.solution.json"
    out.write_text(sol.model_dump_json(indent=2))
    return out


def main():
    STAGING.mkdir(parents=True, exist_ok=True)
    print(f"Packing {len(VARIANTS)} variants into {STAGING}")
    paths = []
    for name, flags in VARIANTS:
        p = _write_variant(name, flags)
        paths.append(p)
        print(f"  {name:16s} -> {p.name}  ({len(flags)} flags)")

    comma = ",".join(str(p) for p in paths)
    print()
    print("Run the sweep:")
    print()
    print(
        f"modal run scripts/run_modal_compare.py --solutions "
        f'"{comma}" --repeats 3 --output '
        f"artifacts/flag_sweep_3repeats.json"
    )


if __name__ == "__main__":
    main()
